/*
 * Writes js/version.js with the short hash of the latest commit that touched anything other than
 * js/version.js itself, so stamping and committing the result doesn't change the stamped value.
 * A trailing "+" marks uncommitted changes. Run `node scripts/stamp-version.js` before committing a release.
 */
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const git = function (args) { return execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim(); };
const exclude = ':(exclude)js/version.js';

const hash = git(['log', '-1', '--format=%h', '--', '.', exclude]);
const dirty = git(['status', '--porcelain', '--', '.', exclude]) !== '';
const build = hash + (dirty ? '+' : '');

fs.writeFileSync(path.join(root, 'js', 'version.js'),
  "/* HL7Forge — build stamp, generated by scripts/stamp-version.js. */\nwindow.HL7FORGE_BUILD = '" + build + "';\n");
console.log('Stamped build ' + build);
